import Foundation

/// Names the cause behind repeated plugin repairs, when it's the phase older Tuist generated, and
/// says from the installed Tuist whether the fix is to upgrade or only to regenerate.
struct MacroCopyPhaseCheck: Check {
    let id = "xcode-mcp/macro-copy-phase"
    let title = "No in-place macro copy phase"
    static let fixedIn = Version("4.203")

    func run(_ context: CheckContext) async -> CheckResult {
        let projects = MacroCopyPhase.projects(in: context.project)
        guard !projects.isEmpty else { return .pass("none") }
        let cause = "\(projects.joined(separator: ", ")) still copy macro plugins in place, which gets them killed: generated by Tuist before 4.203"
        return .warn("\(cause); \(await fix(context))")
    }

    private func fix(_ context: CheckContext) async -> String {
        guard context.runner.which("tuist") != nil else { return "upgrade Tuist and regenerate" }
        let installed = await context.runner.run("tuist", "version").stdout.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !installed.isEmpty else { return "upgrade Tuist and regenerate" }
        // A team usually pins Tuist; saying which one is installed keeps the fix from reading as "change the pin".
        return Version(installed) < Self.fixedIn
            ? "Tuist \(installed) is installed: upgrade to 4.203 or later, then regenerate"
            : "Tuist \(installed) is installed, which no longer adds it: regenerate (tuist install, then tuist generate)"
    }
}
