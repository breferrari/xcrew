import Foundation

/// The project xcrew serves: its root folder and the files xcrew reads or writes there.
public struct Project: Sendable, Equatable {
    public let root: URL

    public init(root: URL) {
        self.root = root.standardizedFileURL
    }

    /// The project mcs or Claude Code names, else the working directory.
    public static func current(machine: Machine = .live) -> Project {
        let path = machine.value("MCS_PROJECT_PATH") ?? machine.value("CLAUDE_PROJECT_DIR") ?? FileManager.default.currentDirectoryPath
        return Project(root: URL(fileURLWithPath: path, isDirectory: true))
    }

    public var mobileBuildMCPConfig: URL { root.appending(path: ".mobilebuildmcp/config.yaml") }
    /// Whether MobileBuildMCP has its per-project config; the doctor and the session briefing both ask.
    public var hasMobileBuildMCPConfig: Bool { FileManager.default.fileExists(atPath: mobileBuildMCPConfig.path) }
    /// Marks the config as xcrew's: setup rewrites a marked config and leaves an unmarked one alone.
    public var managedMarker: URL { root.appending(path: ".mobilebuildmcp/.xcrew-managed") }
    /// Where XcodeBuildMCP kept its config before the rename; no longer read by anything.
    public var legacyConfigFolder: URL { root.appending(path: ".xcodebuildmcp") }
    public var skillsFolder: URL { root.appending(path: ".claude/skills") }

    /// `.xcworkspace` and `.xcodeproj` bundles at the root, workspaces first.
    public var xcodeContainers: [String] {
        let names = (try? FileManager.default.contentsOfDirectory(atPath: root.path)) ?? []
        return names.filter { $0.hasSuffix(".xcworkspace") }.sorted() + names.filter { $0.hasSuffix(".xcodeproj") }.sorted()
    }

    /// Files whose presence marks a project generated by Tuist, whose project files are regenerated.
    public static let tuistMarkers = ["Tuist.swift", "Project.swift", "Workspace.swift", "Tuist"]
    /// The same for Tuist or XcodeGen.
    public static let generatorMarkers = tuistMarkers + ["project.yml"]
    /// Files whose presence marks an Apple-platform project, including generated ones whose workspace may not exist yet.
    static let appleProjectMarkers = ["Package.swift"] + generatorMarkers
    /// Folders that hold other projects' code, never this one's manifests.
    static let dependencyFolders: Set = ["node_modules", "Pods", "Carthage", "DerivedData", "build"]
    /// How far below the root a generator's manifests are looked for: a repository often keeps its app in `ios/` or `apps/ios/`.
    static let manifestDepth = 2

    /// Whether Tuist generates this project, from its manifests at the root or a folder or two below it.
    public var isTuistProject: Bool { hasManifest(Self.tuistMarkers) }

    /// Whether Tuist or XcodeGen generates this project, so its project files are rewritten on each generate.
    public var isGenerated: Bool { hasManifest(Self.generatorMarkers) }

    func hasManifest(_ markers: [String]) -> Bool {
        var folders = [root]
        for depth in 0...Self.manifestDepth {
            if folders.contains(where: { folder in markers.contains { FileManager.default.fileExists(atPath: folder.appending(path: $0).path) } }) { return true }
            guard depth < Self.manifestDepth else { break }
            folders = folders.flatMap(Self.subfolders)
        }
        return false
    }

    /// A folder's own subfolders, leaving out hidden ones and those that hold dependencies.
    static func subfolders(of folder: URL) -> [URL] {
        let names = (try? FileManager.default.contentsOfDirectory(atPath: folder.path)) ?? []
        return names.sorted().filter { !$0.hasPrefix(".") && !dependencyFolders.contains($0) }.map { folder.appending(path: $0) }
            .filter { (try? $0.resourceValues(forKeys: [.isDirectoryKey]).isDirectory) == true }
    }

    public var isApplePlatformProject: Bool {
        !xcodeContainers.isEmpty
            || Self.appleProjectMarkers.contains { FileManager.default.fileExists(atPath: root.appending(path: $0).path) }
    }
}
