import Foundation

/// The project xcrew serves: its root folder and the files xcrew reads or writes there.
public struct Project: Sendable, Equatable {
    public let root: URL
    /// The user's home folder, never searched below even when it's a repository.
    public let home: URL?

    public init(root: URL, home: URL? = nil) {
        self.root = root.standardizedFileURL
        self.home = home?.standardizedFileURL
    }

    /// The project mcs or Claude Code names, else the working directory.
    public static func current(machine: Machine = .live) -> Project {
        let path = machine.value("MCS_PROJECT_PATH") ?? machine.value("CLAUDE_PROJECT_DIR") ?? FileManager.default.currentDirectoryPath
        return Project(root: URL(fileURLWithPath: path, isDirectory: true), home: machine.home)
    }

    public var mobileBuildMCPConfig: URL { root.appending(path: ".mobilebuildmcp/config.yaml") }
    /// Whether MobileBuildMCP has its per-project config; the doctor and the session briefing both ask.
    public var hasMobileBuildMCPConfig: Bool { FileManager.default.fileExists(atPath: mobileBuildMCPConfig.path) }
    /// Marks the config as xcrew's: setup rewrites a marked config and leaves an unmarked one alone.
    public var managedMarker: URL { root.appending(path: ".mobilebuildmcp/.xcrew-managed") }
    /// Where XcodeBuildMCP kept its config before the rename; no longer read by anything.
    public var legacyConfigFolder: URL { root.appending(path: ".xcodebuildmcp") }
    public var skillsFolder: URL { root.appending(path: ".claude/skills") }

    /// `.xcworkspace` and `.xcodeproj` bundles at the root, workspaces first.
    public var xcodeContainers: [String] {
        let names = (try? FileManager.default.contentsOfDirectory(atPath: root.path)) ?? []
        return Self.containerExtensions.flatMap { suffix in names.filter { $0.hasSuffix(suffix) }.sorted() }
    }

    /// The bundles that hold an Xcode workspace or project, workspaces first.
    public static let containerExtensions = [".xcworkspace", ".xcodeproj"]

    static func isXcodeContainer(_ name: String) -> Bool {
        containerExtensions.contains { name.hasSuffix($0) }
    }

    /// Files whose presence marks a project generated by Tuist, whose project files are regenerated.
    public static let tuistMarkers = ["Tuist.swift", "Project.swift", "Workspace.swift", "Tuist"]
    /// The same for Tuist or XcodeGen.
    public static let generatorMarkers = tuistMarkers + ["project.yml"]
    /// Files whose presence at the root marks an Apple-platform project, including generated ones whose workspace may not exist yet.
    /// Below the root a package is more often a tool or a server than an app, so only the generators' manifests count there.
    static let appleProjectMarkers = ["Package.swift"] + generatorMarkers
    /// Folders that hold other projects' code, never this one's manifests.
    static let dependencyFolders: Set = ["node_modules", "Pods", "Carthage", "DerivedData", "build"]
    /// How far below the root projects and manifests are looked for: a repository often keeps its app in `ios/` or `apps/ios/`.
    static let searchDepth = 2

    /// How far below the root this project is searched for an Xcode project: only in a repository, so session start never
    /// walks a folder such as Downloads, and never in the home folder, which dotfiles kept in git make a repository.
    var searchDepth: Int {
        let isRepository = FileManager.default.fileExists(atPath: root.appending(path: ".git").path)
        return isRepository && root != home ? Self.searchDepth : 0
    }

    /// Whether Tuist generates this project, from its manifests at the root or a folder or two below it.
    public var isTuistProject: Bool { hasEntry(upTo: Self.searchDepth) { name, _ in Self.matches(name, Self.tuistMarkers) } }

    /// Whether Tuist or XcodeGen generates this project, so its project files are rewritten on each generate.
    public var isGenerated: Bool { hasEntry(upTo: Self.searchDepth) { name, _ in Self.matches(name, Self.generatorMarkers) } }

    /// Whether this is an Apple-platform project, from an Xcode project or a manifest at the root or, in a repository, a folder or two below it.
    public var isApplePlatformProject: Bool {
        hasEntry(upTo: searchDepth) { name, depth in
            Self.isXcodeContainer(name) || Self.matches(name, depth == 0 ? Self.appleProjectMarkers : Self.generatorMarkers)
        }
    }

    /// Whether `name` is one of `markers`, whatever its case, as the file system finds it.
    static func matches(_ name: String, _ markers: [String]) -> Bool {
        markers.contains { $0.caseInsensitiveCompare(name) == .orderedSame }
    }

    /// Whether the root, or a folder up to `depth` below it, holds an entry that `matches` accepts at that depth.
    /// Hidden folders, bundles and folders that hold dependencies aren't searched.
    func hasEntry(upTo depth: Int, _ matches: (String, Int) -> Bool) -> Bool {
        var folders = [root]
        for level in 0...depth {
            var below: [URL] = []
            for folder in folders {
                let entries = (try? FileManager.default.contentsOfDirectory(at: folder, includingPropertiesForKeys: [.isDirectoryKey], options: .skipsHiddenFiles)) ?? []
                if entries.contains(where: { matches($0.lastPathComponent, level) }) { return true }
                guard level < depth else { continue }
                below += entries.filter {
                    $0.pathExtension.isEmpty && !Self.dependencyFolders.contains($0.lastPathComponent)
                        && (try? $0.resourceValues(forKeys: [.isDirectoryKey]).isDirectory) == true
                }
            }
            folders = below
        }
        return false
    }
}
