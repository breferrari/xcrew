import { expect, mock, test } from 'claude-code/testing'
import type { On } from 'claude-code'
import type { Problem } from './cli'
import { stubCli } from './testing'

const BAND = {
  plugin: 'xcrew',
  component: 'AbovePrompt',
  props: { hasSurvey: false, isWorking: false, maxRows: 10, bodyColumns: 100, scroll: { offset: 0, bodyRows: 10 }, view: {} },
} as const

const COPY_PHASE: Problem = { status: 'warn', id: 'xcode-mcp/macro-copy-phase', message: 'AppMacros still copy macro plugins in place, which gets them killed: generated by Tuist before 4.203; upgrade Tuist and regenerate' }
const NOT_APPROVED: Problem = { status: 'fail', id: 'xcode-mcp/claude-approved', message: "Claude Code isn't approved in Xcode: call XcodeOpenWorkspace and approve it" }

/** Stands for the engine at session start: the doctor prints `problems`, and the band draws nothing of its own. */
function sessionWith(on: On, problems: Problem[]) {
  const clock = mock.clock(on)
  mock.store(on)
  on('session.start', (_, e) => ({ cwd: e.cwd }))
  on('command.register', (_, e) => ({ value: { command: e.name } }))
  on('session.surfaces', () => ({ value: ['terminal'] }))
  on('ui.invalidate', () => ({ value: undefined }))
  on('ui.status', () => ({ value: undefined }))
  const calls = stubCli(on, { problems })
  on('ui.render', ($, e) => {
    const { Text } = $.ui.resolve(e)
    return Text({ children: ['engine'] })
  })
  on('tool.call', () => ({ result: {}, text: 'ok' }))
  return { calls, clock }
}

test('a problem found at session start shows on the band, with where to look', async ($, on) => {
  const { calls, clock } = sessionWith(on, [COPY_PHASE])
  await $.session.start({ cwd: '/work/App', surface: 'terminal', isInteractive: true })
  await clock.settle()

  expect(calls.map(call => call.args)).toContainEqual(['doctor', '--problems', '--json'])
  const ui = await $.ui.mount({ ...BAND, surface: 'terminal' })
  expect((await ui.find({ type: 'Text', text: '⚠' }))?.props.color).toBe('warning')
  expect((await ui.find({ type: 'Text', text: /^ AppMacros still copy macro plugins in place/ }))?.props.color).toBe('warning')
  expect((await ui.find({ type: 'Text', text: ' · /xcrew doctor' }))?.props.color).toBe('subtle')
  await ui.unmount()
})

test('a failure outranks a warning, and the band says how many more there are', async ($, on) => {
  const { clock } = sessionWith(on, [COPY_PHASE, NOT_APPROVED])
  await $.session.start({ cwd: '/work/App', surface: 'terminal', isInteractive: true })
  await clock.settle()

  const ui = await $.ui.mount({ ...BAND, surface: 'terminal' })
  expect((await ui.find({ type: 'Text', text: '⚠' }))?.props.color).toBe('error')
  expect((await ui.find({ type: 'Text', text: /isn't approved in Xcode/ }))?.text).toBe(" Claude Code isn't approved in Xcode: call XcodeOpenWorkspace and approve it")
  expect((await ui.find({ type: 'Text', text: ' (+1 more)' }))).toBeDefined()
  await ui.unmount()
})

test('with nothing wrong the band stays as it was', async ($, on) => {
  const { clock } = sessionWith(on, [])
  await $.session.start({ cwd: '/work/App', surface: 'terminal', isInteractive: true })
  await clock.settle()

  const ui = await $.ui.mount({ ...BAND, surface: 'terminal' })
  expect((await ui.find({ type: 'Text' }))?.text).toBe('engine')
  await ui.unmount()
})

test('once a run starts, the run takes the band and the problem does not come back', async ($, on) => {
  const { clock } = sessionWith(on, [COPY_PHASE])
  await $.session.start({ cwd: '/work/App', surface: 'terminal', isInteractive: true })
  await clock.settle()
  await $.tool.call({ tool: 'mcp__xcode__BuildProject' } as never)
  await clock.advance(4 * 60_000)

  const ui = await $.ui.mount({ ...BAND, surface: 'terminal' })
  expect(await ui.find({ type: 'Text', text: '⚠' })).toBeUndefined()
  await ui.unmount()
})
